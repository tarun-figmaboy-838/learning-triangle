"""Measures when each word is spoken in every narration clip, for word-by-word captions in sync with
the voice (dual coding). Writes js/data/vo-word-times.js: { clipId: [startMs, ...] } (one per word).

How: the clip is decoded to 16 kHz mono PCM (macOS afconvert); a 10 ms loudness envelope marks where
the voice is speaking; the words are laid along that spoken time in proportion to their syllables, so
a word never starts inside a pause and the pauses after commas and full stops land where they are.
Run after recording or replacing clips:  python3 tools/vo_word_times.py
"""
import array
import json
import math
import os
import re
import subprocess
import tempfile
import wave

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
VO_DIR = os.path.join(ROOT, "assets/audio/vo")
LINES = os.path.join(ROOT, "js/data/vo-lines.js")
OUT = os.path.join(ROOT, "js/data/vo-word-times.js")
FRAME_MS = 10
MIN_GAP_MS = 90        # quieter stretches shorter than this are inside a word, not a pause
MIN_VOICED_MS = 40     # louder blips shorter than this are clicks, not speech


def syllables(word):
    word = re.sub(r"[^a-z0-9°]", "", word.lower())
    if not word:
        return 1
    if word.isdigit() or "°" in word:
        return {"2": 1, "3": 1, "90": 2, "90°": 4}.get(word, 2)
    groups = re.findall(r"[aeiouy]+", word)
    count = len(groups) - (1 if word.endswith("e") and len(groups) > 1 and not word.endswith("le") else 0)
    return max(1, count)


def envelope(path):
    with tempfile.TemporaryDirectory() as tmp:
        wav_path = os.path.join(tmp, "clip.wav")
        subprocess.run(["afconvert", path, wav_path, "-f", "WAVE", "-d", "LEI16@16000", "-c", "1"], check=True, capture_output=True)
        with wave.open(wav_path) as wav:
            rate = wav.getframerate()
            samples = array.array("h", wav.readframes(wav.getnframes()))
    step = rate * FRAME_MS // 1000
    return [math.sqrt(sum(s * s for s in samples[i:i + step]) / max(1, len(samples[i:i + step]))) for i in range(0, len(samples), step)]


def voiced_regions(env):
    peak = max(env) or 1
    floor = sorted(env)[len(env) // 10]
    threshold = floor + (peak - floor) * 0.08
    regions, start = [], None
    for i, value in enumerate(env + [0]):
        if value >= threshold and start is None:
            start = i
        elif value < threshold and start is not None:
            regions.append([start, i])
            start = None
    merged = []
    for region in regions:
        if merged and (region[0] - merged[-1][1]) * FRAME_MS < MIN_GAP_MS:
            merged[-1][1] = region[1]
        else:
            merged.append(region)
    return [(a * FRAME_MS, b * FRAME_MS) for a, b in merged if (b - a) * FRAME_MS >= MIN_VOICED_MS]


def word_times(text, regions):
    words = text.split()
    weights = []
    for word in words:
        weight = syllables(word)
        weights.append(weight)
    total_weight = sum(weights)
    spoken = sum(b - a for a, b in regions)
    # Map a position along the spoken (voiced) time to a clock time.
    def clock(position):
        for a, b in regions:
            if position <= b - a:
                return a + position
            position -= b - a
        return regions[-1][1]
    times, acc = [], 0.0
    for i, weight in enumerate(weights):
        start = clock(spoken * acc / total_weight)
        # A word after a comma or full stop starts at the next voiced region, never inside the pause.
        if i and re.search(r"[,.!?]$", words[i - 1]):
            later = [a for a, _ in regions if a >= start - 20]
            start = later[0] if later else start
        if times:
            start = max(start, times[-1] + 90)      # always forward, at least a short beat apart
        times.append(int(round(start)))
        acc += weight
    return times


def main():
    source = open(LINES, encoding="utf-8").read()
    entries = re.findall(r'"([^"]+)":\s*\{\s*id:\s*"([^"]+)",\s*file:\s*"([^"]+)"', source)
    result = {}
    for text, clip_id, filename in entries:
        path = os.path.join(VO_DIR, filename)
        if not os.path.isfile(path):
            continue
        regions = voiced_regions(envelope(path))
        if not regions:
            continue
        result[clip_id] = word_times(text, regions)
        print(f"{clip_id}: {len(text.split())} words, speech {regions[0][0]}..{regions[-1][1]} ms in {len(regions)} runs -> {result[clip_id]}")
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write("/** Generated by tools/vo_word_times.py: when each word starts in each narration clip (ms, at 1x). */\n")
        handle.write("export const VO_WORD_TIMES = Object.freeze(" + json.dumps(result, indent=2) + ");\n")


if __name__ == "__main__":
    main()
